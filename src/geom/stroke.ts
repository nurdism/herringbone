const ADVANCE = 0.78

export function textWidth(text: string, size: number): number {
  return text.length ? (text.length * ADVANCE - (ADVANCE - 0.6)) * size : 0
}

export type TextAlign = 'left' | 'center' | 'right'

/**
 * Lay out a string as polylines. `x`, `y` is the baseline start, adjusted by
 * `align`. Unknown characters fall back to a space.
 */
export function strokeText(
  text: string,
  x: number,
  y: number,
  size: number,
  align: TextAlign = 'center',
  vertical: 'baseline' | 'middle' = 'baseline',
): V2[][] {
  const up = text.toUpperCase()
  const w = textWidth(up, size)
  const ox = align === 'center' ? x - w / 2 : align === 'right' ? x - w : x
  const oy = vertical === 'middle' ? y - size / 2 : y
  const out: V2[][] = []
  for (let i = 0; i < up.length; i++) {
    const glyph = G[up[i]] ?? G[' ']
    const gx = ox + i * ADVANCE * size
    for (const stroke of glyph) {
      out.push(stroke.map(([sx, sy]) => v2(gx + sx * size, oy + sy * size)))
    }
  }
  return out
}
